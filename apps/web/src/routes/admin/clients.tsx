const HERE = "/admin/clients"

/**
 * `/admin/clients` — the registered applications (FR-OIDC-2, **D50**).
 *
 * Two kinds of client live in one table, and the difference is visible rather
 * than inferred:
 *
 * - **From the file.** Declared in `oauth_clients.json` and reconciled at
 *   start-up. Read-only here, and that is the design: a form that edited one
 *   would let an administrator make a change the next restart silently undoes.
 * - **Registered here.** Marked by an owning `userId`, which is exactly the
 *   column reconciliation's orphan sweep skips — so these survive restarts and
 *   the two sets never fight over a row.
 *
 * A created client works immediately: the provider's `getClient` falls back to
 * a database lookup for ids outside its trusted-client cache, so there is no
 * restart in the loop. The one thing that does not follow automatically is the
 * origin set behind CORS and the CSP `form-action` list, which is why every
 * mutation refreshes it (`server/oidc/client-origins.ts`).
 *
 * The secret is generated by the server and shown once, through the same
 * one-shot stash the API keys use — never in the address bar.
 */
export const Route = createFileRoute("/admin/clients")({
  loader: async ({ context, location }) => {
    const search = location.search as Record<string, unknown>
    return {
      ui: context.ui,
      gate: context.gate,
      clients: (await fetchClients()) ?? [],
      notice: searchString(search.notice),
      error: searchString(search.error),
      // Claimed, and therefore consumed: this render is the only one that has
      // the secret, and the row holds nothing but a hash.
      created: await claimAdminSecret({
        data: searchString(search.created) ?? "",
      }),
    }
  },
  component: ClientsPage,
  server: {
    handlers: {
      POST: async ({ request }) => {
        const runtime = await getRuntime()
        const base = runtime.config.base.basePath
        const here = `${base}${HERE}`

        // Registering a client is a credential-minting act, so it sits behind
        // the same freshness gate as every other admin write (FR-AUTH-5).
        const fresh = await requireFreshSession(runtime, request, HERE)
        if (!fresh.ok) return fresh.response

        const { fields: form, list: valuesOf } = await readFormMulti(request)

        if (form.action === "delete") {
          const result = await callAuth(
            runtime,
            "/idp/delete-client",
            { clientId: form.clientId ?? "" },
            request
          )
          if (!result.ok) {
            return redirectWithCookies(withError(here, errorCodeFor(result)))
          }
          return redirectWithCookies(`${here}?notice=clientDeleted`)
        }

        if (form.action === "toggle") {
          const result = await callAuth(
            runtime,
            "/idp/set-client-disabled",
            {
              clientId: form.clientId ?? "",
              disabled: form.disabled === "on",
            },
            request
          )
          if (!result.ok) {
            return redirectWithCookies(withError(here, errorCodeFor(result)))
          }
          return redirectWithCookies(
            `${here}?notice=${form.disabled === "on" ? "clientDisabled" : "clientEnabled"}`
          )
        }

        // Create. One URI per line is what an operator actually has in front of
        // them; the schema wants an array.
        const result = await callAuth(
          runtime,
          "/idp/create-client",
          {
            clientId: form.clientId ?? "",
            name: form.name ?? "",
            type: form.type ?? "spa",
            redirectUris: lines(form.redirectUris ?? ""),
            postLogoutRedirectUris: lines(form.postLogoutRedirectUris ?? ""),
            scopes: valuesOf("scopes"),
            skipConsent: form.skipConsent === "on",
            enableEndSession: form.enableEndSession === "on",
          },
          request
        )
        if (!result.ok) {
          return redirectWithCookies(withError(here, errorCodeFor(result)))
        }

        const secret =
          typeof result.body.clientSecret === "string"
            ? result.body.clientSecret
            : ""
        if (secret === "") {
          // A public client has none, so there is nothing to hand over.
          return redirectWithCookies(`${here}?notice=clientCreated`)
        }
        const handle = await stash(runtime, secret, { ttlSeconds: 600 })
        return redirectWithCookies(`${here}?created=${handle}`)
      },
    },
  },
})

/** A textarea of URIs, one per line, blank lines dropped. */
function lines(value: string): string[] {
  return value
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== "")
}

function ClientsPage() {
  const { ui, gate, clients, notice, error, created } = Route.useLoaderData()
  const t = getCatalog(ui.locale)

  return (
    <AdminShell
      ui={ui}
      t={t}
      title={t.admin.clients.title}
      description={t.admin.clients.description}
      impersonated={gate.admin ? gate.impersonated : false}
      actions={
        <ActionDialog
          label={t.admin.clients.add}
          description={t.admin.clients.addHelp}
          variant="default"
          size="default"
        >
          <PendingForm
            busy={t.common.loading}
            method="post"
            className="grid gap-4"
          >
            <input type="hidden" name="action" value="create" />
            <Field>
              <FieldLabel htmlFor="name">{t.admin.clients.name}</FieldLabel>
              <Input id="name" name="name" required />
            </Field>
            <Field>
              <FieldLabel htmlFor="clientId">
                {t.admin.clients.clientId}
              </FieldLabel>
              <Input
                id="clientId"
                name="clientId"
                required
                autoComplete="off"
                pattern="[A-Za-z0-9._~\-]+"
              />
            </Field>
            <Field>
              <FieldLabel htmlFor="type">{t.admin.clients.type}</FieldLabel>
              {/* SPA first and by default: a browser application is what an
                  operator adds here, and PKCE is mandatory in this provider
                  either way (FR-OIDC-1), so "web" only buys a secret that a
                  single-page app cannot keep. */}
              <NativeSelect
                id="type"
                name="type"
                defaultValue="spa"
                className="w-full"
              >
                <option value="spa">{t.admin.clients.typeSpa}</option>
                <option value="web">{t.admin.clients.typeWeb}</option>
                <option value="native">{t.admin.clients.typeNative}</option>
              </NativeSelect>
            </Field>
            <Field>
              <FieldLabel htmlFor="redirectUris">
                {t.admin.clients.redirectUris}
              </FieldLabel>
              <Textarea
                id="redirectUris"
                name="redirectUris"
                required
                rows={3}
                className="font-mono text-xs"
                aria-describedby="redirect-help"
              />
              <FieldDescription id="redirect-help">
                {t.admin.clients.onePerLine}
              </FieldDescription>
            </Field>
            <Field>
              <FieldLabel htmlFor="postLogoutRedirectUris">
                {t.admin.clients.postLogoutRedirectUris}
              </FieldLabel>
              {/* Read by the handler since D50 and never rendered, so every
                  client created here got an empty list. */}
              <Textarea
                id="postLogoutRedirectUris"
                name="postLogoutRedirectUris"
                rows={2}
                className="font-mono text-xs"
                aria-describedby="post-logout-help"
              />
              <FieldDescription id="post-logout-help">
                {t.admin.clients.onePerLine}
              </FieldDescription>
            </Field>
            <fieldset className="grid gap-2">
              <legend className="mb-1 text-sm font-medium">
                {t.admin.clients.scopes}
              </legend>
              {ui.oauthScopes.map((scope) => (
                <Label
                  key={scope}
                  className="flex items-center gap-2 text-sm font-normal"
                >
                  {/* The wrapping label is Base UI's documented pattern and
                      is what makes the text a click target; `aria-label` is
                      belt-and-braces, because the control the user operates is
                      a `role="checkbox"` span rather than a labelable element,
                      and only labelable elements are named by a wrapping
                      `<label>` per HTML-AAM. */}
                  <Checkbox
                    name="scopes"
                    value={scope}
                    defaultChecked
                    aria-label={scope}
                  />
                  {scope}
                </Label>
              ))}
            </fieldset>
            {/* Both of these were sent by the handler with no field to send
                them from, so a *defined* `false` overrode the schema default
                every time. `skipConsent` therefore defaulted to true in the
                file schema (FR-OIDC-3) and to false for everything created
                here — every admin-registered client wrongly asked for
                consent. It is checked by default now, which restores the
                documented semantics. */}
            <Label className="flex items-start gap-2 text-sm font-normal">
              {/* `aria-describedby`, not just visible text: the control is a
                  `role="checkbox"` span, so neither the wrapping label nor the
                  help underneath it reaches a screen reader on its own. */}
              <Checkbox
                name="skipConsent"
                value="on"
                defaultChecked
                aria-label={t.admin.clients.skipConsent}
                aria-describedby="skip-consent-help"
              />
              <span>
                {t.admin.clients.skipConsent}
                <span
                  id="skip-consent-help"
                  className="block text-xs text-muted-foreground"
                >
                  {t.admin.clients.skipConsentHelp}
                </span>
              </span>
            </Label>
            {/* Unchecked, unlike `skipConsent`: `clients-schema.ts` refuses
                `enableEndSession: true` with no post-logout URI, so defaulting
                it on would fail every plain create. The old always-false bug
                was accidentally load-bearing. */}
            <Label className="flex items-start gap-2 text-sm font-normal">
              <Checkbox
                name="enableEndSession"
                value="on"
                aria-label={t.admin.clients.enableEndSession}
                aria-describedby="end-session-help"
              />
              <span>
                {t.admin.clients.enableEndSession}
                <span
                  id="end-session-help"
                  className="block text-xs text-muted-foreground"
                >
                  {t.admin.clients.enableEndSessionHelp}
                </span>
              </span>
            </Label>
            <SubmitButton>{t.admin.clients.add}</SubmitButton>
          </PendingForm>
        </ActionDialog>
      }
    >
      <FormAlert variant="default">{messageForNoticeCode(notice, t)}</FormAlert>
      <FormAlert>
        {messageForErrorCode(error, t, ui.passwordMinLength)}
      </FormAlert>

      {created ? (
        <SecretDialog
          t={t}
          title={t.admin.clients.secretTitle}
          description={t.admin.clients.secretHelp}
          value={created}
        />
      ) : null}

      {clients.length === 0 ? (
        <Empty>
          <EmptyHeader>
            <EmptyDescription>{t.admin.clients.empty}</EmptyDescription>
          </EmptyHeader>
        </Empty>
      ) : (
        <Card className="overflow-x-auto py-0">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>{t.admin.clients.name}</TableHead>
                <TableHead>{t.admin.clients.type}</TableHead>
                <TableHead>{t.admin.clients.redirectUris}</TableHead>
                <TableHead>{t.admin.clients.scopes}</TableHead>
                <TableHead>{t.admin.clients.skipConsent}</TableHead>
                <TableHead>{t.admin.clients.managedBy}</TableHead>
                <TableHead>{t.admin.clients.status}</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {clients.map((client) => (
                <TableRow key={client.clientId}>
                  <TableCell>
                    <span className="font-medium">{client.name}</span>
                    <code className="block text-xs text-muted-foreground">
                      {client.clientId}
                    </code>
                  </TableCell>
                  <TableCell className="text-xs">
                    {client.type}
                    <span className="block text-muted-foreground">
                      {client.isPublic
                        ? t.admin.clients.public
                        : t.admin.clients.confidential}
                    </span>
                  </TableCell>
                  <TableCell className="text-xs">
                    {client.redirectUris.map((uri) => (
                      <code key={uri} className="block break-all">
                        {uri}
                      </code>
                    ))}
                  </TableCell>
                  <TableCell className="text-xs">
                    {client.scopes.join(" ") || "—"}
                  </TableCell>
                  <TableCell className="text-xs">
                    {client.skipConsent ? (
                      <Badge variant="secondary">{t.common.yes}</Badge>
                    ) : (
                      <span className="text-muted-foreground">
                        {t.common.no}
                      </span>
                    )}
                  </TableCell>
                  <TableCell className="text-xs">
                    <Badge variant="outline">
                      {client.managedBy === "file"
                        ? t.admin.clients.managedFile
                        : t.admin.clients.managedDatabase}
                    </Badge>
                  </TableCell>
                  <TableCell className="text-xs">
                    {client.disabled ? (
                      <Badge variant="destructive">
                        {t.admin.clients.disabled}
                      </Badge>
                    ) : (
                      <Badge variant="secondary">
                        {t.admin.clients.enabled}
                      </Badge>
                    )}
                    {client.managedBy === "database" ? (
                      <div className="mt-2 flex flex-wrap gap-2">
                        <PendingForm busy={t.common.loading} method="post">
                          <input type="hidden" name="action" value="toggle" />
                          <input
                            type="hidden"
                            name="clientId"
                            value={client.clientId}
                          />
                          {client.disabled ? null : (
                            <input type="hidden" name="disabled" value="on" />
                          )}
                          <SubmitButton variant="outline" size="sm">
                            {client.disabled
                              ? t.admin.clients.enable
                              : t.admin.clients.disable}
                          </SubmitButton>
                        </PendingForm>
                        <ActionDialog
                          label={t.admin.clients.remove}
                          description={t.admin.clients.removeConfirm}
                          variant="destructive"
                        >
                          <PendingForm
                            busy={t.common.loading}
                            method="post"
                            className="grid gap-4"
                          >
                            <input type="hidden" name="action" value="delete" />
                            <input
                              type="hidden"
                              name="clientId"
                              value={client.clientId}
                            />
                            <SubmitButton variant="destructive">
                              {t.admin.clients.remove}
                            </SubmitButton>
                          </PendingForm>
                        </ActionDialog>
                      </div>
                    ) : null}
                  </TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </Card>
      )}
    </AdminShell>
  )
}
